['Business profile mastery', <<<'MD'
Your business profile is the highest-leverage asset in local search. Most are half complete.

## Setting up correctly

**Name.** Your actual business name, exactly as it appears on signage. Not the name plus keywords. Keyword stuffing here is a guideline violation, competitors report it, and suspension is disruptive to recover from.

**Address.** Only if customers can visit. If you travel to customers, you are a service-area business and must hide the address. Listing a home address as a visitable storefront is one of the most common suspension triggers.

**Phone.** A local number where possible. Local numbers perform better than national ones for local queries.

**Hours.** Accurate, including holidays. Wrong hours produce a specific and damaging kind of negative review: someone who travelled to a closed business.

## Category selection

The most important single field.

Your primary category constrains which searches you can appear for more than anything else you control.

**How to choose well:**

1. List every category that describes what you do
2. Check what your top three map pack competitors use as their primary
3. Choose the most specific category that covers your core revenue
4. Add secondary categories for genuine additional services
5. Test alternatives, one at a time, measuring for a month

Specific usually beats general. "Dental implants periodontist" reaches a more valuable searcher than "dentist," if it accurately describes you.

## Fields that matter, in order

| Field | Effect | Notes |
| --- | --- | --- |
| Primary category | Very high | Test and measure |
| Reviews | Very high | Covered next chapter |
| Services and products | High | Feeds long-tail relevance |
| Photos, recent | Medium to high | Recency matters more than count |
| Attributes | Varies by category | Decisive for some, ignorable for others |
| Description | Medium | Written for humans, not keywords |
| Posts | Low to medium | Freshness signal |
| Q and A | Medium | Underused, see below |

## Questions and answers

Genuinely underused. You can ask and answer questions on your own profile, and those answers appear prominently.

Seed it with the questions you are actually asked: parking, appointment necessity, payment methods, insurance, languages spoken. Answer them properly.

Also monitor it. Anyone can answer a question on your profile, including a competitor or a mistaken member of the public. Unmonitored Q and A occasionally contains confidently wrong information.

## Photos

- Real photos of your actual premises, team and work
- Exterior shots that help someone recognise the place while looking for it
- Update monthly rather than uploading fifty once
- Geotagging is not a ranking factor, despite persistent claims

Stock photography is recognisable and undermines the authenticity local search rewards.

## Avoiding suspension

Common triggers worth avoiding deliberately:

- Keywords in the business name
- Address that does not match a real, signed, staffed location
- Bulk-editing many fields at once
- Virtual office or coworking address without genuine presence
- Category that misrepresents the business

If suspended: identify and fix the cause first, then appeal with documentation. Appealing without fixing wastes the attempt.
