## Citation consistency

A citation is any mention of your business name, address and phone number. Their ranking weight has decreased over the years, but inconsistency still causes real harm.

**The reason:** conflicting information prevents confident consolidation of your business as a single entity.

**The approach:**

1. Establish your canonical format. Exact name, exact address format, one phone number.
2. Audit where you already appear. Search your business name, phone number, and address separately.
3. Fix inconsistencies, starting with the highest-authority platforms.
4. Build citations only on platforms that genuinely matter for your country and category.

Ignore services promising hundreds of citations. Thirty accurate, relevant listings outperform four hundred low-quality ones, and cleaning up the four hundred later is expensive.

## Priority platforms

1. The major search and map platforms for your country
2. The dominant local directory in your market
3. Category-specific directories your buyers actually use
4. Chambers of commerce and trade associations
5. Data aggregators feeding smaller directories

## Location pages that earn their place

If you have one location, your homepage and contact page can serve. With multiple, each needs its own page with genuinely distinct content.

**What legitimately differs:**

- The team at this location, named
- Services available here, which vary more than head office assumes
- Actual hours including local variation
- Parking, transport, landmarks, entrance
- Reviews from this location
- Photos of this location
- Branch-specific FAQs

**Structure:**

1. H1 with brand and location naturally phrased
2. Opening that answers what you do here and how to book
3. NAP block with LocalBusiness schema
4. Booking or enquiry action, visible immediately
5. Services here
6. The team here
7. Getting here, practically
8. Reviews from this branch
9. FAQs with FAQPage schema

## Local content that works

Beyond location pages, content that reinforces local relevance:

- **Service plus location pages,** but only where genuine search demand exists. Do not generate the full matrix speculatively.
- **Local guides** relevant to your service. A removals company writing about neighbourhoods is credible; a dentist doing so is not.
- **Case studies with local context,** naming the area and the specific situation.
- **Community involvement,** which produces genuine local links and mentions.

The test for any local content idea: would a local person find this useful, or is it only there for a search engine? The second kind stopped working some years ago.

## Local links

Links from local sources carry weight for local relevance:

- Local news coverage
- Chambers and business associations
- Sponsorships of local events or teams
- Supplier and partner pages
- Local blogs and community sites

These are usually easier to earn than national links and more relevant to local ranking.
