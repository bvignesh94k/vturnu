['Reviews and reputation', <<<'MD'
Reviews are the most direct lever on both ranking and conversion, and the one most businesses leave to chance.

## What matters, in order

1. **Recency.** A steady stream beats a large old stack.
2. **Volume relative to local competitors.** Your position in the local set, not the absolute number.
3. **Rating.** Above 4.2 the gain flattens; below 4.0 conversion suffers noticeably.
4. **Response rate.** Signals an active business, visible to readers and platform.
5. **Content.** Reviews mentioning specific services reinforce relevance for those terms.

A business with 40 reviews from the last six months usually outranks one with 200 from three years ago.

## Building a review habit

Programmes fail when asking depends on remembering. Build it into the process.

**Timing.** At the moment of peak satisfaction: immediately after the successful outcome, not at month end.

**The ask.** Specific beats generic. "Would you mind mentioning which service you had and how it went?" produces reviews containing the terms that help you rank and the detail that helps other buyers decide.

**The route.** A direct link by SMS or WhatsApp. Every extra step loses a meaningful share of people who intended to.

**The target.** A modest monthly number, consistently met. Four a month is 48 a year, which changes your competitive position in most local markets.

!NOTE Do not filter reviewers by asking satisfaction first and only routing happy customers to the public form. It breaches platform policy and can result in losing your entire review corpus.

## Responding well

Respond to everything, within 48 hours.

**Positive:** short, specific, mention the service naturally, thank them by name.

**Negative:** the response is not for the reviewer. It is for the next fifty people reading it while deciding whether to call you.

1. Acknowledge without defensiveness
2. Apologise for the experience
3. State what you are doing about it
4. Offer to continue offline with a real contact
5. Never argue details publicly

A measured response to a poor review frequently reads better than an unbroken wall of five stars, because it demonstrates how you behave when something goes wrong.

## Fake and unfair reviews

You will receive them.

1. Report through the platform, citing the specific policy breached
2. If it remains, respond factually, noting you have no record of the interaction
3. Outweigh with volume, which is the most reliable remedy

Never buy reviews. Detection has improved substantially and the penalty affects the whole profile.

## Reviews beyond the primary platform

Depending on your category, other platforms carry weight with buyers even where they do not affect map rankings: sector-specific directories, marketplace listings, and social recommendations.

Prioritise by where your buyers actually look, which is usually a shorter list than the full universe of review sites.
