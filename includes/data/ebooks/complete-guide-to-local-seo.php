Local search runs on a different system from organic search, with different inputs. Understanding the separation is what stops you applying organic tactics to a local problem and wondering why nothing moves.

## Two result sets, two systems

A local query returns two things.

**The map pack:** three business listings with a map. Driven primarily by your business profile, not your website.

**Organic results:** the standard blue links below. Driven by your website, as usual.

You can rank first organically and be absent from the map pack, or the reverse. They are separate competitions and often need separate work.

For most local businesses the map pack matters more, because it sits above organic results and captures the calls and directions requests.

## The three ranking factors

Local ranking rests on three inputs, and getting the weighting right saves a great deal of wasted effort.

### Relevance

How well your profile matches the query. Driven by:

- Primary category, the single largest lever
- Secondary categories
- Services and products listed
- The words in your profile description and reviews

### Distance

How close you are to the searcher, or to the location named in the query.

**This is the factor you cannot change,** and understanding that prevents a lot of frustration. You will not rank in the map pack for a suburb fifteen kilometres away with no presence there. Any agency promising otherwise is describing something that does not work that way.

What distance means practically: your visibility has a radius. The work grows that radius. It does not relocate it.

### Prominence

How well known and well regarded the business is:

- Review count and recency
- Review rating
- Citation consistency across the web
- Links to your site
- Organic authority of your domain
- Engagement with your profile

!STAT Category and reviews | account for most of the movement available to you. Distance is fixed and prominence builds slowly, so start with the two you control directly.

## What this means for effort allocation

Given the three factors, effort should go roughly:

1. **Primary category and profile completeness.** Fastest and largest effect.
2. **Reviews: count, recency, response.** Second largest, ongoing.
3. **Citation consistency.** Necessary hygiene, one-time plus maintenance.
4. **Location page and local content.** Supports organic and reinforces relevance.
5. **Links and general authority.** Slowest, still worth doing.

Most local businesses do five and neglect one and two.

## The realistic expectation

Local SEO produces movement faster than most SEO disciplines. A neglected profile that is properly optimised often shows measurable change within four to eight weeks, because profile signals update quickly.

What takes longer: growing your radius, overtaking established competitors with hundreds of reviews, and building the prominence that holds the position.
