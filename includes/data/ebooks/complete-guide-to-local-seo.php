## Why gridded rank tracking matters

Local rankings vary by the searcher's exact position. A single reported rank is close to meaningless, because it describes one point.

Grid tracking samples a matrix of points across your target area and shows where you appear and where you do not. The output is a map of your actual visibility radius.

That radius is the real objective. Growing it from two kilometres to five is a substantial commercial gain that a single-point rank report would not show at all.

## Calls are the metric that matters

For most local businesses, calls from the profile are the closest thing to a direct revenue metric.

Track them properly:

- Use the profile's own call reporting
- Consider call tracking with a dynamic number, though note that a mismatched number can affect NAP consistency; use a provider that handles this correctly
- Record call outcomes so you can measure lead quality, not just volume

## A monthly review

1. Profile views, calls and direction requests, month on month
2. Gridded position: has the radius grown?
3. Reviews added, current rating, response rate
4. Which queries produced profile views, from the performance report
5. Competitor movement in the map pack
6. One change to make next month

## Realistic timelines

- **Weeks 1 to 4:** profile optimisation, citation cleanup. Some early movement.
- **Weeks 4 to 12:** category and completeness effects settle. Review programme begins to accumulate.
- **Months 3 to 6:** review volume and consistency compound. Radius grows.
- **Months 6 and beyond:** prominence builds through links and sustained review velocity.

## Common mistakes

1. **Keyword stuffing the business name.** Short-term gain, suspension risk.
2. **Ignoring reviews** while doing everything else.
3. **Expecting to rank far outside your actual location.** Distance is not negotiable.
4. **Mass citation building** on low-quality directories.
5. **Duplicate profiles** left unmerged.
6. **Templated location pages** that differ only by city name.
7. **Measuring one rank position** instead of a visibility radius.
