## The photo discipline

Photo freshness correlates with engagement, and engagement correlates with placement. Set a standard: each location uploads three to five genuine photos monthly. Exterior with signage, interior, team, work in progress.

Stock photography is worse than nothing. It is recognisable and it undermines the authenticity that local search rewards.

## Handling duplicates and suspensions

Both are inevitable at scale. Have a process ready before you need it.

**Duplicates** arise from old listings, previous owners, or automated creation. Search your brand plus each address, claim or report duplicates, and merge into the canonical profile.

**Suspensions** happen. The recovery path:

1. Identify the likely trigger. Usually name keyword stuffing, address issues, or an unusual bulk edit.
2. Fix the underlying issue before appealing. Appealing without fixing wastes the attempt.
3. Submit the appeal with documentation: utility bill, signage photo, registration.
4. Escalate through the support forum if the first appeal fails.

**Prevention beats cure:** avoid bulk-editing many locations in one session, keep names clean, and ensure every address has genuine signage and staffed presence.

