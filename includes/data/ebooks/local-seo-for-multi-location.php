| --- | --- |
| New reviews this month | Meets branch target |
| Rolling average rating | Above 4.2 |
| Response rate | 100% |
| Median response time | Under 48 hours |
| Rank versus local competitor set | Improving |

Publish this internally by branch. Visibility drives compliance more effectively than instruction.
