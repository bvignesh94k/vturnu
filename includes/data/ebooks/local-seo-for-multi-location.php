['Location pages and per-branch reporting', <<<'MD'
Your location pages are where local search meets your website. They are also the most commonly wasted asset in a multi-location estate.

## Why templated pages fail

A page that differs from nineteen others only by city name provides nothing a search engine wants to rank. Worse, at scale it signals a pattern of low-value content.

The fix is not spinning text. It is including information that genuinely varies by location.

## What actually differs, and should be on the page

- The specific team at that branch, named, with photos
- Services available here, which usually vary more than head office assumes
- Actual opening hours including local holidays
- Parking, public transport, landmarks, floor and entrance
- Reviews from this branch, displayed on this page
- Photos of this location, not the flagship
- Local pricing where it differs
- Area served, described in terms locals recognise
- Branch-specific FAQs

That is enough for a genuinely distinct page without inventing anything.

## Page structure

1. **H1 with brand plus location** in natural language
2. **Direct answer opening:** what you do here, who for, and how to book
3. **NAP block** matching the canonical record exactly, with LocalBusiness schema
4. **Booking or enquiry action,** visible without scrolling
5. **Services at this branch**
6. **The team here**
7. **Getting here,** with practical detail
8. **Reviews from this location**
9. **Branch FAQs** with FAQPage schema
10. **Link to the parent service pages**

## URL structure

Two patterns work. Pick one and keep it.

`/locations/anna-nagar/` for a single-service brand.

`/dental-implants/anna-nagar/` when you need service-by-location coverage.

The second scales into many more pages and only makes sense with genuine demand for each combination. Do not generate the full matrix speculatively.

## Schema

Every location page needs LocalBusiness or the appropriate subtype, containing:

- Name, address, phone matching the canonical record
- Geo coordinates
- Opening hours in structured form
- Price range where applicable
- Link back to the Organization entity as parent
- The specific profile URL as sameAs

The parent link matters at scale. It states explicitly that these twenty locations belong to one organisation, which helps consolidate authority instead of fragmenting it.

## Per-branch reporting

This is where multi-location programmes are won or lost managerially.

Report by location, never averaged:

| Metric | Source | Why |
| --- | --- | --- |
| Profile views and actions | Business profile insights | Local visibility |
| Calls from profile | Profile call tracking | Direct revenue signal |
| Direction requests | Profile insights | Physical intent |
| Location page sessions | Analytics, by URL | Website contribution |
| Enquiries from page | Form tracking with branch field | Conversion |
| Review count and rating | Profile | Programme compliance |
| Map pack position | Local rank tracking, geo-gridded | Competitive position |

**Geo-gridded rank tracking deserves explanation.** Local rankings vary by the searcher's exact position. A single reported rank is nearly meaningless. Grid tracking samples a matrix of points around each branch and shows the radius over which you actually appear. That radius is your real catchment, and growing it is the actual objective.

## Finding the outliers

Each month, sort branches by performance and look at both ends.

**Bottom performers:** is it profile quality, review deficit, page problems, or genuine local competition? The cause is usually visible within ten minutes of comparing against the top branch.

**Top performers:** what are they doing that others are not? Multi-location programmes improve fastest by propagating what already works internally rather than importing new tactics.
