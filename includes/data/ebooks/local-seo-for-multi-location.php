['The review programme', <<<'MD'
Reviews are the most direct lever on local visibility and the one most often left to chance. A programme beats enthusiasm.

## What actually matters

Four dimensions, roughly in order:

1. **Recency.** A stream of recent reviews outperforms a larger stack of old ones.
2. **Volume relative to local competitors.** Absolute count matters less than your position in the local set.
3. **Rating.** Above roughly 4.2 the marginal gain flattens. Below 4.0 conversion suffers noticeably.
4. **Response rate.** Responding signals an active business and is visible to both readers and the platform.

A branch with 40 reviews from the last six months typically outperforms one with 200 reviews from three years ago.

## Building the ask into operations

Programmes fail when asking depends on someone remembering. Build it into the workflow instead.

**Pick the moment of peak satisfaction.** Not month end. Immediately after the successful outcome: treatment completed, delivery received, problem solved.

**Make the ask specific.** "Would you mind leaving a review?" gets vague responses. "Would you mind mentioning which treatment you had and how the appointment went?" produces reviews containing the terms that help you rank and the detail that helps other buyers.

**Remove friction.** A direct link to the review form, sent by WhatsApp or SMS. Every additional step loses a meaningful share.

**Set a per-branch target.** A modest number, consistently. Four a month at twenty branches is nearly a thousand reviews a year across the estate.

!NOTE Never gate reviews by asking for satisfaction first and only routing happy customers to the public form. It violates platform policy and, when detected, can remove your entire review corpus.

## Responding

Respond to everything. Aim within 48 hours.

**Positive reviews.** Brief, specific, mention the service naturally, thank them by name. Three sentences.

**Negative reviews.** The response is not for the reviewer. It is for the next fifty people who read it while deciding.

1. Acknowledge without defensiveness
2. Apologise for the experience, not necessarily the facts
3. State what you are doing about it
4. Move the detail offline with a real contact
5. Never argue specifics publicly

A calm, specific response to a poor review often reads better than a wall of five stars, because it is evidence of how you behave when something goes wrong.

## Fake and unfair reviews

You will get them. Options, in order:

1. Report through the platform, citing the specific policy breached
2. Respond factually if it stays up, noting you have no record of the interaction
3. Outweigh with volume, which is the most reliable remedy

Do not buy reviews. Detection has improved substantially and the penalty falls on the whole estate.

