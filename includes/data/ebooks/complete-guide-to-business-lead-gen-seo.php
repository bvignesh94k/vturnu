['Pipeline measurement', <<<'MD'
B2B SEO programmes are cancelled in budget meetings, not in execution, and almost always because nobody could connect them to pipeline.

## Why attribution is genuinely hard here

State it honestly rather than promising precision:

- Cycles run months, spanning many touchpoints
- Buying committees research separately
- Much research is anonymous until a late form fill
- Forwarded links and private conversations leave no trace
- **Last-click credits the final branded search** that content created

That last point deserves emphasis. Last-click attribution systematically undercredits SEO in long-cycle businesses.

## What to measure instead

### 1. Self-reported attribution

One optional field: "How did you hear about us?"

Unscientific, and consistently the most useful data available. People write things like "I read your comparison of you and [competitor]" that no tracking captures.

### 2. Influenced pipeline

Of opportunities created this quarter, what share had at least one organic touchpoint before the first sales conversation? Requires analytics connected to the CRM, and it is the number that survives finance scrutiny.

### 3. Money-page rankings

The leading indicator. Are you ranking for alternatives, comparison, pricing and integration terms? These rankings precede pipeline by weeks.

### 4. Content-assisted close rate

Do leads who consumed content close at a higher rate? Frequently yes, which is a stronger argument than volume.

### 5. Cycle length

Do deals where the buyer read your material close faster? Shortening the cycle is worth as much as adding leads.

## The reporting format

One page monthly:

| Metric | Reading |
| --- | --- |
| Influenced pipeline value | Deals with an organic touchpoint |
| Qualified leads from organic | CRM, not form fills |
| Money-page rankings | Leading indicator |
| Self-reported mentions | Qualitative evidence |
| Sales usage | Whether content is used in deals |

Then one sentence on what changes next month.

Excluded deliberately: sessions, bounce rate, time on page. Reporting them invites the wrong conversation.

## Setting expectations before you start

Agree in writing:

- **Months 1 to 3:** money pages published and indexed. First rankings on low-competition terms. Enquiries possible, not reliable.
- **Months 3 to 6:** money-page terms ranking consistently. Attributable pipeline appears.
- **Months 6 to 12:** solution content compounds. Organic becomes predictable.
- **Beyond 12:** authority lifts new content faster.

A programme judged at month two on traffic will be cancelled before the mechanism that makes it work has operated.

## The offline conversion loop

If you run paid alongside organic, feed qualified leads back to the ad platforms as offline conversions. Bidding then optimises for lead quality rather than form fills, which typically changes performance more than any other single intervention.
