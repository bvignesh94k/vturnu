['The money-page layer', <<<'MD'
These are the pages that produce enquiries. Build them before anything else.

## Alternatives pages

Someone searching "[competitor] alternatives" is in market, dissatisfied, and evaluating. The highest intent query in B2B.

**Structure:**

1. Direct answer: the main alternatives, listed immediately
2. Honest assessment of each, including the competitor named in the query
3. Where each option genuinely fits best
4. Where you fit best, and where you do not
5. A comparison table
6. Clear next step

**The credibility requirement.** List real alternatives, including ones better than you for particular cases. A page claiming every alternative is inferior is transparently self-serving and readers discount the whole thing.

Naming where you lose makes every other claim believable. It also disqualifies poor-fit prospects before they consume sales time, which is a benefit rather than a cost.

## Comparison pages

"[You] vs [Competitor]." Cover the dimensions buyers actually weigh:

- Pricing model and total cost
- Implementation time and effort
- Support model
- Integrations
- Scale limits
- Best-fit customer profile

A table plus a paragraph on each dimension. Conclude with a recommendation by scenario, not a blanket claim.

## Pricing pages

The most consequential page most B2B sites refuse to build properly.

If you cannot publish exact prices, publish:

- The pricing model and what drives cost up or down
- Typical ranges by customer size or scope
- What is included and what costs extra
- A worked example with real numbers
- What happens on renewal

Silence produces two outcomes, both bad: the buyer assumes a price that may be wrong, or they leave to find the answer on a review site framed by someone else.

## Integration pages

Trivial to produce and consistently underrated. One page per meaningful integration:

- What it does
- How to set it up
- What data flows, in which direction
- Limitations, stated honestly

Very high intent, negligible competition.

## Use-case pages

"[Category] for [industry or role]." Lets the reader recognise themselves.

Each needs genuine specificity: the problems in that context, the language that industry uses, a relevant example. A template with the industry name swapped in fails for the same reason templated location pages fail.

## Service and solution pages

The commercial core.

1. **Direct answer in the first 60 words.** What this is and what it produces.
2. **Who it is for, and who it is not for.** Naming the exclusion is disproportionately persuasive.
3. **What is included.** Concrete deliverables.
4. **Process.** Week one, month one, ongoing.
5. **Proof from this specific service.**
6. **Pricing signal.**
7. **FAQ** answering the objections sales actually hears.
8. **Clear action.**
