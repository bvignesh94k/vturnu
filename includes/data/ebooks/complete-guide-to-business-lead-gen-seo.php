Above the money pages sits the layer that captures buyers before they know which vendor they need.

## Solution-aware content

The buyer knows they have a problem and is researching approaches, not yet vendors.

The discipline this requires: **cover approaches that are not your product.**

An article on "ways to reduce customer churn" that presents only your software is recognised as marketing and dismissed. One that honestly covers process changes, pricing changes, service improvements and software, then explains where software helps and where it does not, is trusted, and the trust carries into the vendor stage.

## Problem-aware content

Earlier still. The buyer has symptoms and has not diagnosed the cause.

"Why do enterprise deals stall at procurement" reaches someone who has not yet concluded they need anything. Wider audience, longer payback, builds the topical authority that lifts everything else.

Fund this only after the money-page layer is producing.

## Making content usable by sales

The most underused asset in B2B content.

Sales answers the same objections daily. Content answering those objections should exist, and sales should send it during deals.

**Build the loop:**

1. Ask sales for the ten questions they answer most
2. Write the definitive answer to each
3. Give sales the links and a note on when to send each
4. Ask quarterly which ones actually help

This closes the circle: sales questions become content, and content shortens the cycle.

## The originality requirement

Content assembled from other articles has no original claim, so nothing can cite it. That is the structural reason aggregated content does not earn citations or links.

Sources of genuine originality:

1. **Your own data.** Aggregate and anonymise benchmarks from your client base.
2. **Original testing.** Run it, report what happened, including failures.
3. **Documented process.** Your actual method, in followable detail.
4. **Named frameworks.** A model others can cite.
5. **Practitioner interviews.** Perspective only doing the work produces.

## Gating: when and when not

The reflex is to gate everything. It costs more than it returns in most cases.

**Do not gate** content that should rank, be cited, or be shared. A gate blocks crawlers and kills the distribution.

**Gate** genuinely high-value assets where the exchange is fair: original research, calculators, templates, comprehensive guides.

**A useful pattern:** publish the content ungated so it ranks and gets cited, and offer a downloadable version for people who want to keep it. You get both the visibility and the leads.
