['Voice, and making it survive a team', <<<'MD'
Visual identity is easy to enforce because deviation is visible. Voice is where brands actually fragment, because everyone writes and few notice the drift.

## Defining voice usefully

"Professional yet approachable" is not a definition. Everyone thinks their writing is both.

Define voice as a set of choices with examples:

| Dimension | Our choice | Not this |
| --- | --- | --- |
| Formality | Plain and direct | Corporate or slangy |
| Confidence | Specific claims with evidence | Hedging, or unearned superlatives |
| Technicality | Explain the term, then use it | Assume knowledge, or oversimplify |
| Length | As short as the idea allows | Padding to seem thorough |
| Humour | Dry, rare, never at a reader's expense | Constant jokes, or none at all |

Then, critically, show pairs. Before and after, weak and strong, for the same message. Examples teach voice. Adjectives do not.

## The words list

Two short lists, more useful than any style essay.

**Words we use:** the terms your buyers use, your named frameworks, the specific verbs you prefer.

**Words we avoid:** jargon your buyers do not use, empty intensifiers, claims you cannot evidence.

Most companies should ban: leverage as a verb, synergy, world-class, cutting-edge, best-in-class, revolutionary, seamless, robust, delve, and any sentence beginning "In today's fast-paced."

## The specificity rule

The single highest-impact rule you can set: **replace adjectives with numbers wherever a number exists.**

- "Significantly improved performance" becomes "cut load time from 4.1s to 1.6s"
- "Many clients" becomes "eleven clients in this sector"
- "Fast turnaround" becomes "first draft within five working days"

This does more for perceived credibility than any tone guidance, and it is easy to check in review.

## Voice across contexts

The same brand should sound recognisably itself while adapting to the situation.

- **Website:** clear, confident, structured for scanning
- **Email:** warmer, more direct, written to one person
- **Proposals:** precise, specific, no marketing language
- **Support:** plain, patient, solution-first
- **Social:** shorter, more opinionated, still specific
- **Error messages:** apologetic, clear about what to do next

Error messages are worth naming explicitly. They are read at the moment of maximum frustration and are almost always written by whoever built the form.

## Keeping voice consistent

1. **A one-page guide** with pairs of examples, not a manual
2. **Templates** for the formats produced most often
3. **A review step** for anything customer-facing, at least initially
4. **Named ownership**, someone who cares about the writing
5. **A feedback loop:** when something reads wrong, add it to the avoid list

The realistic goal is not perfection. It is that a reader encountering three pieces from different people recognises the same company.
