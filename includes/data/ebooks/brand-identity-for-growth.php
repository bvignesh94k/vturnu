['Positioning is a choice about who you lose', <<<'MD'
Brand work usually starts with a logo. It should start with a decision about who you are not for, and most companies never make that decision.

## What positioning actually is

Positioning is the answer to one question: **when a buyer has a specific problem, why should they choose you over the alternative?**

Three parts, all required:

1. A specific buyer
2. A specific problem
3. A specific reason you are the better answer

If any is missing you do not have positioning. You have a description.

## Why "we serve everyone" is expensive

The instinct is that narrowing loses business. In practice, breadth costs more.

A broad position produces:

- Marketing that resonates with nobody strongly enough to act
- Sales conversations that start from scratch every time
- Pricing pressure, because you compete on price when nothing else distinguishes you
- Product decisions pulled in conflicting directions

A narrow position produces the opposite. Fewer conversations, more of them qualified, less price resistance because the fit is obvious.

!STAT The narrowing test | If your positioning statement could sit on a competitor's website unchanged, it is not positioning.

## The positioning statement

One sentence, four variables:

> For **[specific buyer]** who **[specific situation]**, we provide **[category]** that **[specific outcome]**, unlike **[the realistic alternative]**.

The last variable is where most attempts collapse. The alternative is rarely a named competitor. Usually it is:

- Doing nothing
- Doing it in-house
- A freelancer
- A generic large provider
- A cheap tool

Name the real alternative. It changes the whole argument. Competing against "doing nothing" requires a case for urgency. Competing against in-house requires a case for expertise. These are different messages entirely.

## Working out your actual differentiation

Ask three questions honestly.

**1. What do you do that competitors genuinely cannot copy quickly?**

Not "quality" or "service." Structural advantages: a proprietary method, specific domain depth, a delivery model, an unusual team composition, a data asset.

**2. What do your best clients say when asked why they chose you?**

Ask ten of them. The answer is frequently not what the leadership team believes it is, and it is usually more specific and more mundane.

**3. What are you willing to be bad at?**

The uncomfortable one, and the most revealing. A firm that is genuinely fast is usually not also the cheapest. A firm that is genuinely deep is usually not also the broadest.

Naming your trade-off is what makes the positioning credible.

## Testing it

A position is working when:

- The right prospects say "that is exactly our situation" unprompted
- The wrong prospects self-select out before consuming sales time
- Your team can state it consistently without reading it
- Price objections decrease relative to fit conversations

If none of that changes after a repositioning, the position was cosmetic.
