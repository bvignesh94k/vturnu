['A visual system, not a logo', <<<'MD'
A logo is one asset. A visual system is the set of rules that lets a hundred assets look like they came from one company, made by people who were not in the room when it was designed.

## What a usable system contains

Most brand deliverables are a logo file and a colour swatch. That is why consistency collapses within months.

A system that survives contact with a real team defines:

- **Logo**, with variants for every real context and clear-space rules
- **Colour**, with defined roles, not just values
- **Type**, with a scale and rules for when to use each level
- **Spacing**, on a consistent scale
- **Components**, at least buttons, cards, forms and navigation
- **Imagery**, with a stated treatment
- **Motion**, with a shared duration and easing vocabulary
- **Voice**, covered in the next chapter

## Colour with roles

The most common failure. A palette of eight colours with no guidance produces eight different interpretations.

Define by function instead:

| Role | Purpose | Count |
| --- | --- | --- |
| Primary | Main brand presence, primary actions | 1 |
| Secondary | Support, secondary actions | 1 |
| Accent | Highlight, used sparingly | 1 to 2 |
| Neutral | Text, borders, backgrounds | 4 to 6 steps |
| Semantic | Success, warning, error | 3 |

Then specify usage: which colour for a primary button, which for body text, which never appears on a large surface.

**Check contrast before adopting a palette.** A brand colour that fails WCAG AA against white is a colour you cannot use for text, and discovering that after launch means either an inaccessible site or an off-brand one.

## Typography that scales

One family with a wide weight range is usually better than two families. It reduces load, guarantees harmony, and removes the most common inconsistency.

Define a scale rather than picking sizes case by case. A ratio-based scale produces hierarchy that holds at any screen size.

Then state the rules: which level for page titles, which for section headings, what line length body text should hold to, when to switch weight rather than size.

## Designing for the real contexts

Systems break because they were designed for a presentation and used somewhere else. Design and test for:

- Small sizes, where a detailed logo becomes noise
- Dark backgrounds, where a dark logo disappears
- Single colour, for print, stamps and embroidery
- Square crops, for social avatars
- Very wide crops, for banners
- Low quality reproduction, where thin strokes vanish

Producing these variants at the outset costs a fraction of retrofitting them later.

## Documentation people actually use

A hundred-page PDF gets read once. What gets used:

- A one-page summary covering the eighty percent case
- Downloadable assets in the formats people actually need, correctly named
- Examples of correct usage, and specific examples of incorrect usage
- A named person who answers questions

The "incorrect usage" section is disproportionately effective. Showing the stretched logo, the wrong colour combination and the mixed typeface prevents more errors than any amount of prescription.
