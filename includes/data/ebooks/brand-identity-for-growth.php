['Rollout and governance', <<<'MD'
A brand refresh that is designed but not governed reverts within a year. This chapter is about making it hold.

## Sequencing the rollout

Doing everything simultaneously guarantees inconsistency during the transition. Sequence by visibility.

**Phase 1: Core digital.** Website, email signatures, social profiles. Highest visibility, fastest to change, and it sets the reference everyone else copies from.

**Phase 2: Sales and marketing assets.** Proposals, decks, case studies, one-pagers. This is where sales teams improvise if you leave a gap, so provide templates before, not after.

**Phase 3: Product and interface.** Where applicable, apply the system to the product itself.

**Phase 4: Physical.** Print, signage, packaging, merchandise. Slowest and most expensive, so last.

Set a cutover date for phase 1 and hold it. A half-rebranded website is worse than either version alone.

## Migration risks worth planning for

If the rebrand includes a domain change or significant site restructure, this is where measurable damage occurs.

- Map every existing URL to a specific new one. Never bulk-redirect to the homepage.
- Keep redirects permanently, not for six months.
- Update the canonical entity references, schema and profiles together, not gradually.
- Update every directory, review platform and social profile in the same week, because inconsistency during transition suppresses entity consolidation.
- Expect a temporary dip and communicate that expectation in advance.

## Governance that works

The determining factor in whether a brand holds is whether anyone owns it.

1. **A named owner** with authority to say no
2. **A single source for assets** that is genuinely easier to use than someone's desktop folder
3. **Templates for the top ten recurring formats**
4. **A short review step** for external material
5. **A quarterly audit:** sample recent output and check drift

That fifth item catches the slow decay: a slightly different blue, a second typeface, a stretched logo. Each individually minor, collectively the reason brands look inconsistent after two years.

## Measuring brand

Brand is measurable, though not with the immediacy of a campaign.

| Signal | Source | Reading |
| --- | --- | --- |
| Branded search volume | Search Console | Demand for you specifically |
| Direct traffic share | Analytics | People arriving deliberately |
| Self-reported "heard of you" | Enquiry form | Prior awareness |
| Win rate against named competitors | CRM | Competitive strength |
| Price resistance frequency | Sales notes | Pricing power |
| Time to close | CRM | Whether trust arrives earlier |

**Price resistance is the most direct commercial measure.** Brand strength shows up as fewer conversations about discount and more about fit.

## The honest expectation

Brand work does not produce a measurable lift next month. What it produces:

- Sales conversations that start warmer
- Marketing that compounds instead of restarting
- Less price competition
- Easier hiring
- Faster recognition in a crowded category

Those show up over quarters, not weeks. Anyone promising otherwise is selling a campaign and calling it a brand.
