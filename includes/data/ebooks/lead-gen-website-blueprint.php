['Why most business websites do not produce enquiries', <<<'MD'
A website that does not generate enquiries is rarely broken. It is usually well designed, loads fine, and describes the company accurately. It just fails at one job: making a specific person believe that contacting you is the obvious next step.

## The four failures we find repeatedly

### 1. The site talks about the company, not the problem

Open most agency, consultancy or service websites and the first thing you read is who they are. Founded in, team of, passionate about, committed to excellence.

The visitor did not arrive wanting your history. They arrived with a problem and a hypothesis that you might solve it. Every sentence spent on your story before you have addressed their problem is a sentence spent on the wrong subject.

### 2. There is no single, obvious next step

A homepage with nine calls to action has none. Get a quote, book a call, download the brochure, join the newsletter, follow us, view case studies, contact us, chat now, request a demo. Each competes with the others and the visitor resolves the conflict by doing nothing.

### 3. The proof is generic

"Trusted by leading brands" with six grey logos proves nothing. A specific claim with a number, a timeframe and a named context proves a great deal.

### 4. The form asks for too much, too early

An eleven-field form on a first visit is a filter, and it filters out the people who were merely interested. Some filtering is deliberate and good. Most of it is accidental.

## The mental model that fixes this

A visitor arrives with three questions, in a fixed order. Answer them in that order and enquiries follow. Answer them out of order and they leave.

1. **Am I in the right place?** Within about three seconds.
2. **Can you actually do this?** Proof, specificity, evidence.
3. **What happens if I contact you?** Risk reduction before the ask.

Most sites answer question two well, question one vaguely, and question three not at all.

!STAT 3 seconds | is roughly the window you have to answer "am I in the right place" before a visitor forms a judgement

## What "in the right place" means concretely

Your above-the-fold area needs to communicate, without scrolling:

- What you do, in the words your buyer uses
- Who it is for
- What outcome it produces
- One action to take next

That is four pieces of information. Most heroes contain a slogan and a stock photo.

**Weak:** "Innovative solutions for the digital age"

**Strong:** "SEO and paid campaigns for Indian manufacturers who need qualified export enquiries, not traffic"

The second is narrower. Narrower converts better, because the right person recognises themselves immediately and the wrong person leaves without wasting anyone's time.

## The honest trade-off

Specificity costs you reach. A homepage that names a segment will feel exclusionary to everyone outside it.

That is the point. A website that speaks to everyone produces enquiries from people you cannot serve profitably, and your sales time gets consumed disqualifying them. The narrow site produces fewer, better conversations.
