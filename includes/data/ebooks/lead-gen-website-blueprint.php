['Page anatomy that converts', <<<'MD'
This chapter gives you the structural template for the four page types that carry a lead-generation site.

## The homepage

The homepage is a routing page. Its job is to orient and direct, not to explain everything.

**1. Hero.** The four elements from chapter one. One primary action, one secondary at most.

**2. Proof strip.** Immediately below the fold. Client names, real ratings, or a single credible number. This is the fastest trust signal available.

**3. The problem, named.** Two or three sentences describing the situation the visitor is in, accurately enough that they think "yes, that is exactly it."

**4. What you do, in three to six blocks.** Each with a specific outcome, not a service label. "SEO" is a label. "Rank for the terms your buyers actually search, and get cited by AI engines" is an outcome.

**5. Evidence.** One or two case results with real numbers and context.

**6. How it works.** Three or four steps. This reduces the fear of the unknown that stops people contacting.

**7. Differentiation.** Why you rather than the alternative, stated in a way a competitor could not copy verbatim onto their own site. If they could, it is not differentiation.

**8. Close.** The primary action again, with risk reduction attached.

## The service page

This is where commercial intent lands from search, and it is usually the most neglected template on the site.

**1. Direct answer.** What this service is and what it produces, in the first sixty words. This serves both the visitor and the answer engines.

**2. Who it is for and who it is not for.** Naming who it is not for is disproportionately persuasive. It signals that you are not just trying to close everyone.

**3. What is included.** Concrete deliverables, not vague capability statements.

**4. Process.** What happens week one, month one, ongoing.

**5. Proof specific to this service.** A case result from this discipline, not a general one.

**6. Pricing signal.** A range, a starting point, or the honest reason you cannot publish one. Silence on price is the single biggest cause of drop-off on service pages.

**7. FAQ.** The objections your sales team hears, answered in writing.

**8. Close.**

## The case study

Most case studies are written as company achievements. They should be written as recognition documents: the reader should see their own situation.

- **Situation.** The client's context and the constraint, in enough detail to be recognisable.
- **What was actually wrong.** The diagnosis, including anything counterintuitive.
- **What was done.** Specifics. Vague "we implemented a strategy" wastes the format.
- **Result.** Numbers, timeframe, and what was measured.
- **What we would do differently.** Optional, rare, and enormously credible.

## The contact page

Treated as a formality on most sites, which is a mistake given it is the page closest to revenue.

- Restate what happens next, with a timeframe you actually hit
- Show the form immediately, not below three paragraphs
- Offer an alternative channel: phone, WhatsApp, email
- Remove navigation distractions where you reasonably can
- Set expectations: who replies, how fast, what they will ask

!NOTE Add one sentence above your form describing exactly what happens after submission. In our testing this consistently lifts completion rates, because the main hesitation at that moment is uncertainty about what you are signing up for.
