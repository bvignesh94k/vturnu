['Proof, pricing and the trust layer', <<<'MD'
Structure and forms get you the mechanics. Trust decides whether anyone uses them.

## The proof hierarchy

Not all evidence is equal. Ranked by persuasive power:

1. **Specific results with named context.** "Cut cost per lead 41% for a Chennai edtech platform in one term."
2. **Named client testimonials with role and company.**
3. **Third-party ratings** on platforms buyers already trust.
4. **Client logos**, only if recognisable to your specific audience.
5. **Certifications and partner badges.**
6. **Team credentials and named experts.**
7. **Anonymous testimonials.** Weak, but better than nothing.
8. **Self-declared superlatives.** Zero value, and mild negative signal.

Most sites lead with four and five, and never do one properly.

## Making numbers credible

An impressive number with no context reads as marketing. The same number with method attached reads as evidence.

**Weak:** "300% growth"

**Strong:** "Organic sessions rose from 4,100 to 16,800 a month over nine months, measured in Search Console, alongside a 2.4x rise in enquiry volume."

The second is longer. It is also believable, which the first is not.

## Handling the pricing question

Most service businesses hide pricing and lose enquiries to the uncertainty. The reasons given are usually: it varies, competitors will see it, we will be judged on price alone.

The counter-argument is straightforward. The visitor is going to determine your rough price band regardless, by asking someone or by assuming. An assumption you did not shape is worse than a range you did.

Options in order of preference:

1. **Publish real ranges** with what drives them up or down
2. **Publish a starting point:** "Retainers begin at X for Y scope"
3. **Publish typical project bands** by size
4. **Explain honestly why you cannot publish**, then give a worked example

Anything is better than silence.

## Risk reversal

Reduce the perceived cost of contacting you.

- State that the first conversation is free and unpushy, then honour it
- Give something of value regardless of outcome, such as an audit they keep
- Be explicit about no lock-in, if true
- Name the response time
- Say who will reply, ideally with a name

## Trust signals that matter at the moment of decision

Placement matters as much as content. Trust signals in the footer do nothing. The same signals beside the form work.

Near the primary action, include:

- The response time commitment
- A privacy assurance in plain language
- One relevant proof point
- The alternative contact channel

## The credibility audit

Open your homepage and count. How many claims could a competitor copy word for word onto their own site with no changes? Every one of those is a claim doing no work.

Replace them with things only you can say: your numbers, your named clients, your specific method, your actual guarantee.
