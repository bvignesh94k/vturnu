['Producing content that experts respect', <<<'MD'
Most B2B content fails not because of strategy but because of production. It reads as though written by someone who has never done the job, because it usually was.

## The expert interview method

The highest quality-to-effort process we have found. It solves the two hardest problems at once: getting real expertise onto the page, and doing so without consuming days of an expert's time.

### The process

**1. Identify the expert.** Someone inside the company who actually does the work. Solutions engineer, implementation lead, senior practitioner. Not the marketing team.

**2. Prepare specific questions.** Not "tell me about X." Ask questions only a practitioner can answer:

- What do customers get wrong about this most often?
- What is the first thing you check?
- What is the failure mode nobody expects?
- What do you tell people who have already tried and failed?
- What would you do differently with half the budget?

**3. Record a 30-minute conversation.** Not a written brief. Speech produces specificity that writing prompts do not.

**4. Transcribe and mine.** One good interview typically yields enough substance for two or three pieces.

**5. Write, then return it for correction.** The expert corrects factual errors. They do not rewrite the prose. Keeping those roles separate is what makes this sustainable.

### Why it works

- Real expertise, including the counterintuitive parts
- Genuine examples with specifics
- The vocabulary practitioners actually use
- Thirty minutes of expert time instead of days

## What separates expert content from generic content

Read any two pieces on the same subject and the difference is visible immediately.

| Generic | Expert |
| --- | --- |
| Lists the standard steps | Says which step people skip and what happens |
| "It depends on your needs" | "If you have under 50 users, do X, because Y" |
| Describes best practice | Describes what actually happens in practice |
| No numbers | Specific numbers with conditions |
| No opinion | A clear recommendation with reasoning |
| Avoids competitors | Names them and assesses honestly |

The pattern: **generic content describes, expert content decides.**

## The originality requirement

Answer engines and readers both reward content containing something that exists nowhere else. Sources of genuine originality, in order of effort:

1. **Your own data.** Aggregate, anonymise, publish benchmarks from your client base.
2. **Original testing.** Run the experiment and report what happened, including failures.
3. **Documented process.** Your actual method, in enough detail to be followed.
4. **Named frameworks.** A model that organises the problem, which others can cite.
5. **Practitioner interviews.** Perspective that only comes from doing the work.

Content assembled from other articles has no original claim, so nothing can cite it as a source. That is the structural reason aggregated content does not earn citations.

## A sustainable cadence

Two substantial pieces a month, each better than the current best result, beats eight thin pieces. Thin content does not compound and it dilutes topical authority.

A workable monthly rhythm for a small team:

- Week 1: one expert interview, 30 minutes
- Week 2: draft and review piece one
- Week 3: draft piece two from the same interview
- Week 4: update two existing pieces, distribute

Updating existing content is the most underrated activity here. Refreshing a piece that already ranks usually returns more than publishing a new one.
