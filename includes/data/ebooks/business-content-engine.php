['Bottom of funnel first, and why everyone does it backwards', <<<'MD'
The standard content playbook starts at the top: publish broad awareness content, build an audience, nurture them downward. It is intuitive, it is what most guides recommend, and for B2B companies under a certain size it is close to the worst possible sequence.

## The problem with top-down

Top-of-funnel content has three properties that hurt a company that needs pipeline now.

**It takes longest to pay back.** A reader researching "what is supply chain visibility" may buy in eighteen months, or never.

**It is the most competitive.** Broad terms attract every publisher in the category, including media companies whose entire business is ranking for them.

**It produces the least readable signal.** Traffic rises, nobody can connect it to revenue, and the budget gets cut in the next planning cycle.

Meanwhile the terms that indicate active buying, with far lower volume and far less competition, sit unclaimed.

## The inversion

Publish in reverse order of funnel position.

**Stage 1: Bottom of funnel.** Comparison, alternatives, pricing, integration, implementation. Low volume, high intent, thin competition.

**Stage 2: Middle.** Solution-aware content. How to solve the problem your product solves, including approaches that are not your product.

**Stage 3: Top.** Problem-aware and category content. Highest volume, longest payback, most competitive.

Do them in that order. Stage 1 produces pipeline within weeks and funds the patience required for stage 3.

!STAT 10 to 200 | monthly searches is typical for the bottom-funnel terms that produce most B2B pipeline. Volume is a poor proxy for value.

## The bottom-funnel content types

Ranked by how reliably they produce qualified enquiries:

### 1. Alternatives pages

"[Competitor] alternatives." Someone searching this is actively dissatisfied with a named vendor. There is no earlier signal of purchase intent.

Write it honestly. List real alternatives including ones better than you for certain cases. The credibility gained is what converts the reader who fits you.

### 2. Comparison pages

"[You] vs [Competitor]." They have a shortlist and you are on it. Cover the dimensions buyers actually weigh: price, implementation time, support, integrations, and where each wins.

A comparison claiming you win every dimension is discounted immediately by any experienced buyer.

### 3. Pricing content

Buyers search for pricing constantly and most B2B sites refuse to discuss it. A page explaining pricing model, what drives cost up or down, and typical ranges captures that search and pre-qualifies the enquiry.

### 4. Integration and compatibility

"Does X work with Y." Extremely high intent, almost no competition, trivial to write, and it removes a specific blocker.

### 5. Use-case pages

"[Product category] for [specific industry or role]." Specific enough to convert, and it lets the reader see themselves.

## Why teams resist this

The objections are predictable and worth addressing directly.

**"The volume is too low to matter."** Twenty searches a month at 10% conversion, at a contract value of ten lakh rupees, is a strong month. Volume is a proxy metric. Pipeline is the real one.

**"Naming competitors gives them attention."** Buyers already know your competitors. Refusing to discuss them means the comparison happens on a competitor's page or a review site, framed by someone else.

**"We cannot publish honest weaknesses."** You can, and it is the most persuasive thing on the page. A stated limitation makes every other claim more believable.
