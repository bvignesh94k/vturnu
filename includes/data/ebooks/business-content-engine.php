['Attribution and proving content works', <<<'MD'
Content programmes die in budget meetings, not in execution. The cause is nearly always an inability to connect publishing to pipeline.

## Why B2B attribution is genuinely hard

Be honest about this internally rather than promising precision you cannot deliver.

- Sales cycles run months, and the touchpoints span them
- Buying committees mean several people research separately
- Much research is anonymous until a late form fill
- Dark social, forwarded links and private conversations leave no trace
- Last-click attribution credits the final branded search, which content created

The last point is worth stating plainly: **last-click attribution systematically undercredits content.** The reader found you through a guide, researched for weeks, then searched your brand name and converted. Last-click awards the win to branded search.

## What to measure instead

### 1. Self-reported attribution

Add one optional field to your enquiry form: "How did you hear about us?"

Imperfect, unscientific, and consistently more informative than the analytics model. People say things like "I read your comparison page" that no tracking would capture.

### 2. Influenced pipeline

Of the opportunities created this quarter, what share had at least one content touchpoint before the first sales conversation? This requires connecting analytics to your CRM, and it is the number that survives scrutiny.

### 3. Content-assisted conversion rate

Compare close rates of leads who consumed content before enquiring against those who did not. If content-touched leads close better, content is qualifying as well as attracting, which is a stronger argument than volume.

### 4. Sales cycle length

Do deals where the buyer read your material close faster? Frequently yes, and shortening the cycle is worth as much as adding leads.

### 5. Search visibility for commercial terms

A leading indicator. Are you ranking for the bottom-funnel terms from chapter one? Those rankings precede pipeline by weeks.

## A reporting format that survives budget review

One page, monthly:

| Metric | Reading |
| --- | --- |
| Influenced pipeline value | Deals with a content touchpoint |
| Self-reported content mentions | Direct qualitative evidence |
| Bottom-funnel rankings | Leading indicator |
| Assistant and organic entries to commercial pages | Traffic that matters |
| Sales team usage | Whether the content is used in deals |

Deliberately absent: total pageviews, time on page, bounce rate. They are not decision-relevant and including them invites the wrong conversation.

## Setting expectations before you start

Agree these numbers in advance, in writing, so month three is not a crisis.

- **Months 1 to 3:** Bottom-funnel pieces published and indexed. First rankings on low-competition terms. Early enquiries possible but not reliable.
- **Months 3 to 6:** Bottom-funnel terms ranking consistently. Attributable pipeline appears. Sales begins using the material.
- **Months 6 to 12:** Middle-funnel content compounds. Organic becomes a predictable source.
- **Beyond 12 months:** Topical authority lifts new content faster. This is where the compounding shows.

A programme judged at month two on traffic will be cancelled before the mechanism that makes it work has had time to operate.
