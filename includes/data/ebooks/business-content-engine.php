['Distribution: publishing is not the finish line', <<<'MD'
A piece published and left alone reaches a fraction of its potential audience. Distribution is not promotion at the end. It is part of the production plan.

## The distribution stack

For each substantial piece, plan these before writing.

### 1. Search

The compounding channel. Requires the piece to target a real query, answer directly, and be internally linked from relevant existing pages.

Internal linking is the most neglected step. A new piece with no internal links is orphaned and will take far longer to rank.

### 2. Email

Your owned audience. Do not send a link with "new blog post." Send the single most useful idea from the piece, then link for the rest.

### 3. LinkedIn

For B2B, the highest-return social channel by a wide margin. Rules that hold consistently:

- Post the substance natively, not a link with no context
- Personal profiles outperform company pages substantially
- The first two lines determine whether anyone expands
- Encourage the expert who was interviewed to post their own view

### 4. Sales enablement

The most underused distribution channel in B2B. Your sales team answers the same questions daily. Content that answers those questions should be in their hands, and they should send it during deals.

This closes the loop: the questions sales hears become the content, and the content shortens the sales cycle.

### 5. Communities

Where your buyers actually discuss the problem. Participate genuinely for months before linking to anything. Drive-by link dropping gets you removed and damages the brand.

### 6. Answer engines

Increasingly the distribution surface that matters. Content structured to answer directly, with clear provenance, gets cited in AI answers. Covered in more depth in our AI Search Playbook.

## The update programme

Content decays. Rankings slide, facts go stale, screenshots age.

Run a quarterly review:

1. Pull every piece ranking positions 4 to 15. These are the closest to meaningful gains.
2. For each, compare against what currently outranks it. What does that page cover that yours does not?
3. Update substantively: new sections, refreshed data, better structure. Not a date change.
4. Re-link internally from newer content.
5. Track for six weeks.

In most B2B accounts we manage, updates outperform new publishing on return per hour.

## Repurposing without dilution

One substantial piece supports:

- A LinkedIn post series, one idea per post
- An email sequence
- A sales one-pager
- A short video where the expert explains the core point
- A section in a larger guide or e-book

The constraint: each format must stand alone. Reposting the same text everywhere trains your audience to ignore you.
