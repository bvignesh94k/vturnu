#!/usr/bin/env bash
# Rebuilds assets/js/hero3d.min.js (the homepage WebGL hero) from bin/hero3d/.
# Bundles only the parts of three.js the scene uses. Run from the repo root.
# The land mask in bin/hero3d/landmask.js is regenerated with --mask.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK"
npm init -y >/dev/null
npm install --silent three@0.186.1 esbuild@0.24.2 >/dev/null
if [ "${1:-}" = "--mask" ]; then
  npm install --silent world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1 >/dev/null
  cat > mask.mjs <<'JS'
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';
const topo = JSON.parse(readFileSync('./node_modules/world-atlas/land-110m.json'));
const land = feature(topo, topo.objects.land);
const W = 360, H = 180, bytes = new Uint8Array(W * H / 8);
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++)
  if (geoContains(land, [-179.5 + x, 89.5 - y])) { const i = y * W + x; bytes[i >> 3] |= 1 << (i & 7); }
writeFileSync(process.argv[2], '/* Generated by bin/build-hero3d.sh from Natural Earth 110m land (public domain): 360x180, 1 bit per degree. */\nexport const LAND_W = 360, LAND_H = 180;\nexport const LAND_B64 = "' + Buffer.from(bytes).toString('base64') + '";\n');
JS
  node mask.mjs "$ROOT/bin/hero3d/landmask.js"
fi
cp "$ROOT"/bin/hero3d/*.js .
npx esbuild hero3d.js --bundle --format=esm --minify --target=es2019 --legal-comments=none \
  --outfile="$ROOT/assets/js/hero3d.min.js"
ls -l "$ROOT/assets/js/hero3d.min.js"
